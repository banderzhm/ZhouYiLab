constexpr uint16_t branch_bit(const DiZhi branch) {
  return static_cast<uint16_t>(1U << static_cast<unsigned>(branch));
}

constexpr uint16_t branches(const DiZhi first, const DiZhi second) {
  return branch_bit(first) | branch_bit(second);
}

constexpr uint16_t branch(const DiZhi value) { return branch_bit(value); }

