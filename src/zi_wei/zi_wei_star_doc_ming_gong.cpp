/**
 * @brief 以主星资料表和守命星系条目组成常规报告分段。
 * @param rule 已匹配的守命星系规则。
 * @return 组合结构、主星取象、取用重心与吉煞裁断四段资料。
 */
vector<MingGongAnalysisSection>
default_ming_gong_sections(const MingGongRule &rule) {
  const auto profile =
      ranges::find_if(kPrimaryStarProfiles, [&rule](const auto &item) {
        return item.star == rule.primary_star;
      });
  if (profile == kPrimaryStarProfiles.end()) {
    return {{"宫位结构", string(rule.description)},
            {"会照取用", "须以命宫三方四正、星曜亮度、四化与辅煞会照同参。"},
            {"吉煞裁断",
             "吉曜可扶主星之用，羊陀、火铃、空劫及化忌等则须按所在宫位与"
             "冲会关系细分，不以单星预断。"}};
  }

  vector<MingGongAnalysisSection> sections;
  sections.reserve(rule.companion_star.empty() ? 4 : 5);
  sections.push_back({"星系结构", string(rule.description)});
  if (!rule.companion_star.empty()) {
    const auto companion =
        ranges::find_if(kCompanionStarProfiles, [&rule](const auto &item) {
          return item.primary_star == rule.primary_star &&
                 item.companion_star == rule.companion_star;
        });
    if (companion != kCompanionStarProfiles.end())
      sections.push_back({"同宫关系", string(companion->relationship)});
  }
  sections.push_back({"主星取象", string(profile->essence)});
  sections.push_back({"取用重心", string(profile->focus)});
  sections.push_back({"吉煞裁断", string(profile->caution)});
  return sections;
}

