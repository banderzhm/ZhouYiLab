optional<MingGongDocument> get_ming_gong_document(const vector<string> &stars,
                                                  const DiZhi branch) {
  const auto iterator =
      ranges::find_if(kMingGongRules, [&stars, branch](const auto &rule) {
        return matches(rule, stars, branch);
      });
  if (iterator == kMingGongRules.end())
    return nullopt;
  static constexpr array<string_view, 12> kBranchNames = {
      "子", "丑", "寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌", "亥"};
  const auto title =
      string(iterator->primary_star) + string(iterator->companion_star) +
      (iterator->companion_star.empty() ? "星" : "") +
      string(kBranchNames[static_cast<size_t>(branch)]) + "守命宫";
  auto document = MingGongDocument{title, string(iterator->summary),
                                   string(iterator->description)};
  document.sections = default_ming_gong_sections(*iterator);
  if (iterator->primary_star == "紫微" && iterator->companion_star.empty() &&
      (branch == DiZhi::Zi || branch == DiZhi::Wu)) {
    document.sections = zi_wei_single_sections(branch);
  }
  if (iterator->primary_star == "天同" && iterator->companion_star.empty() &&
      (branch == DiZhi::Si || branch == DiZhi::Hai)) {
    document.sections = tian_tong_si_hai_sections(branch);
  }
  return document;
}

