bool has_star(const vector<string> &stars, const string_view name) {
  return ranges::any_of(stars,
                        [name](const string &star) { return star == name; });
}

bool matches(const MingGongRule &rule, const vector<string> &stars,
             const DiZhi branch) {
  if ((rule.branches & branch_bit(branch)) == 0 ||
      !has_star(stars, rule.primary_star))
    return false;
  if (rule.companion_star.empty())
    return stars.size() == 1;
  return stars.size() == 2 && has_star(stars, rule.companion_star);
}

