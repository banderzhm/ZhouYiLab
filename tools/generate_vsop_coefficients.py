"""Extract numeric VSOP coefficients from a locally pinned reference source.

Usage: python tools/generate_vsop_coefficients.py path/to/astronomy.c
Only numeric tables are imported. Their upstream MIT notice is preserved.
"""
import pathlib
import hashlib
import re
import sys

root = pathlib.Path(__file__).resolve().parents[1]
source_bytes = pathlib.Path(sys.argv[1]).read_bytes()
if hashlib.sha256(source_bytes).hexdigest() != "388920479d819713963ffd0f8ab0677944f66c6c94239ceddddd3b0d5d064432":
    raise ValueError("Reference must be unmodified Astronomy Engine v2.1.19 astronomy.c")
source = source_bytes.decode("utf-8-sig")
planets = "Mercury Venus Earth Mars Jupiter Saturn Uranus Neptune".split()
terms = []
groups = []
for planet in planets:
    planet_groups = []
    for coordinate, axis in enumerate(("lon", "lat", "rad")):
        pattern = rf"static const vsop_term_t vsop_{axis}_{planet}_(\d+)\[\]\s*=\s*\{{(.*?)\}};"
        matches = re.findall(pattern, source, re.S)
        if not matches:
            raise ValueError(f"Missing {planet} {axis}")
        for power, body in matches:
            begin = len(terms)
            for row in re.findall(r"\{([^{}]+)\}", body):
                values = [v.strip() for v in row.split(",")]
                if len(values) != 3:
                    raise ValueError(row)
                for value in values:
                    float(value)
                terms.append("{" + ", ".join(values) + "}")
            planet_groups.append(f"{{{coordinate}, {power}, {begin}, {len(terms)}}}")
    groups.append(planet_groups)
notice = """// Numeric coefficients and frame rotation derived from Astronomy Engine v2.1.19.
// Copyright (c) 2019-2023 Don Cross <cosinekitty@gmail.com>
// MIT license retained in assets/licenses/astronomy-engine-MIT.txt.
// Generated by tools/generate_vsop_coefficients.py. Do not edit manually.
struct OrbitTerm { double amplitude, phase, frequency; };
struct OrbitGroup { int coordinate, power, begin, end; };
"""
output = notice + "static const OrbitTerm orbit_terms[] = {\n" + ",\n".join(terms) + "\n};\n"
# A vector-free view keeps the numeric data independent of C++ module attachment.
output += "struct OrbitGroups { const OrbitGroup* first; const OrbitGroup* last; const OrbitGroup* begin() const { return first; } const OrbitGroup* end() const { return last; } };\n"
for i, group in enumerate(groups):
    output += f"static const OrbitGroup groups_{i}[] = {{" + ",".join(group) + "};\n"
output += "static const OrbitGroups orbit_groups[] = {\n"
output += ",\n".join(f"{{groups_{i}, groups_{i} + {len(group)}}}" for i, group in enumerate(groups))
output += "\n};\n"
(root / "src/astrology/vsop_coefficients.inc").write_text(output, encoding="utf-8")
print(f"Extracted {len(terms)} numeric terms for {len(planets)} planets")
